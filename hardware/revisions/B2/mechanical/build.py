def run(view,out,extra=None):
 cmd=[str(OPENSCAD),'-D','view='+json.dumps(view),'-o',str(out)]
 if extra:cmd+=extra
 cmd+=[str(ROOT/'enclosure.scad')]
 p=subprocess.run(cmd,stdout=subprocess.PIPE,stderr=subprocess.STDOUT,text=True)
 return {'view':view,'returncode':p.returncode,'log':p.stdout,'command':cmd}

def triangles(path):
 b=path.read_bytes()
 if len(b)>=84 and 84+50*struct.unpack('<I',b[80:84])[0]==len(b):
  n=struct.unpack('<I',b[80:84])[0]
  for i in range(n):
   f=struct.unpack('<12fH',b[84+i*50:134+i*50]);yield [tuple(f[j:j+3]) for j in [3,6,9]]
 else:
  verts=[tuple(float(x) for x in line.split()[1:4]) for line in b.decode().splitlines() if line.lstrip().startswith('vertex ')]
  assert len(verts)%3==0
  for i in range(0,len(verts),3):yield verts[i:i+3]

def mesh_check(path):
 ts=list(triangles(path));edges=Counter();directions=Counter();volume=0;points=[]
 for a,b,c in ts:
  vs=[tuple(round(x,5) for x in v) for v in [a,b,c]];points+=vs
  for i in range(3):
   p,q=vs[i],vs[(i+1)%3];edges[tuple(sorted((p,q)))]+=1;directions[(p,q)]+=1
  volume+=(a[0]*(b[1]*c[2]-b[2]*c[1])+a[1]*(b[2]*c[0]-b[0]*c[2])+a[2]*(b[0]*c[1]-b[1]*c[0]))/6
 bad=[(e,n) for e,n in edges.items() if n!=2]
 oriented=all(directions[(a,b)]==directions[(b,a)] for a,b in edges)
 bounds=[[min(v[i] for v in points) for i in range(3)],[max(v[i] for v in points) for i in range(3)]]
 result={'triangles':len(ts),'watertight_edge_counts':not bad,'consistent_winding':oriented,
         'positive_signed_volume':volume>0,'volume_mm3':round(volume,3),'bounds_mm':bounds,
         'size_mm':[round(bounds[1][i]-bounds[0][i],5) for i in range(3)]}
 if not all(result[k] for k in ['watertight_edge_counts','consistent_winding','positive_signed_volume']):
  raise ValueError((path,result))
 return result

